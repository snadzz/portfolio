    "from sklearn.linear_model import LogisticRegression\n",
    "from sklearn.ensemble import RandomForestClassifier\n",
    "from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, precision_score\n",
    "from sklearn.tree import DecisionTreeClassifier\n",
    "from sklearn.neighbors import KNeighborsClassifier\n",
    "from sklearn.model_selection import GridSearchCV\n",
    "import joblib\n",
    "\n",
    "#preprocessing Pipeline\n",
    "num_cols = ['Age', 'agent_rating', 'call_hour']\n",
    "cat_cols = ['Race', 'Gender', 'city', 'employed', 'mobile', 'qualification', 'product']\n",
    "\n",
    "preprocessor = ColumnTransformer([\n",
    "        ('num', StandardScaler(), num_cols),\n",
    "        ('cat', OneHotEncoder(handle_unknown='ignore'), cat_cols)\n",
    "    ])\n",
    "\n",
    "models = {\n",
    "    'Logistic Regression': LogisticRegression(max_iter=1000),\n",
    "    'Random Forest': RandomForestClassifier(n_estimators=100, random_state=42),\n",
    "    'Decision Tree': DecisionTreeClassifier(random_state=42),\n",
    "    'KNN': KNeighborsClassifier(n_neighbors=5)\n",
    "}\n",
    "\n",
    "print(\"--- INITIAL BENCHMARK ---\")\n",
    "for name, model in models.items():\n",
    "    clf = Pipeline([('prep', preprocessor), ('model', model)])\n",
    "    clf.fit(X_train, y_train)\n",
    "    preds = clf.predict(X_test)\n",
    "    print(f\"{name} -> Accuracy: {accuracy_score(y_test, preds):.4f} | Precision: {precision_score(y_test, preds):.4f}\")\n",
    "\n",
    "# --- ADJUST & TUNE (Hyperparameter Tuning on Random Forest) ---\n",
    "rf_pipeline = Pipeline([('prep', preprocessor), ('model', RandomForestClassifier(random_state=42))])\n",
    "\n",
    "param_grid = {\n",
    "    'model__n_estimators': [50, 100, 200],\n",
    "    'model__max_depth': [8, 15, None],\n",
    "    'model__min_samples_split': [2, 10]\n",
    "}\n",
    "\n",
    "grid = GridSearchCV(rf_pipeline, param_grid, cv=3, scoring='precision', n_jobs=-1)\n",
    "grid.fit(X_train, y_train)\n",
    "\n",
    "best_model = grid.best_estimator_\n",
    "tuned_preds = best_model.predict(X_test)\n",
    "print(\"\\n--- AFTER TUNING (WINNER: RANDOM FOREST) ---\")\n",
    "print(f\"Tuned Accuracy: {accuracy_score(y_test, tuned_preds):.4f} | Tuned Precision: {precision_score(y_test, tuned_preds):.4f}\")\n",
    "\n",
    "# Save the winning model to a file\n",
    "joblib.dump(best_model, 'call_center_model.pkl')"
